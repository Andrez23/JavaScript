//Con "Variables" podemos almacenar información para usarla más adelante.

var nombre = "Juan"; //Declaramos una variable llamada "nombre" y le asignamos el valor "Juan"
console.log(nombre); //Mostramos el valor de la variable "nombre" en consola


/*No solo tenemos "var" para crear variables, también tenemos "let" y "const"*/

//Ejemplo con "let"
let edad = 30;
console.log(edad); //Mostramos el valor de la variable "edad" en consola, que es la manera correcta de declarar variables que pueden cambiar su valor a lo largo del tiempo, como la edad de una persona.

//Ejemplo con "const"
const PI = 3.1416;
console.log(PI); //Mostramos el valor de la variable "PI" en consola.Ademas de ello, las constantes no se pueden modificar una vez que se les asigna un valor, por lo que es útil para valores que no deben cambiar, como el valor de PI.